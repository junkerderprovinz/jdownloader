#!/usr/bin/env bash
# -----------------------------------------------------------------------------
# jdownloader-language.sh <iso-code|system>
# -----------------------------------------------------------------------------
# Setzt die UI-Sprache für JDownloader 2.
# Aufgerufen von init-jdownloader bei jedem Container-Start.
#
# JDownloader speichert die Sprache in:
#   cfg/org.appwork.utils.locale.WTFLocale.json  (JD-interner Sprach-Code)
# -----------------------------------------------------------------------------
set -e

CODE="${1:-en}"
JD_DIR="${JD_INST_DIR:-/config/JDownloader}"
JD_CFG="${JD_DIR}/cfg"
PROFILE_D="/config/.profile.d"
ENV_FILE="${PROFILE_D}/jdownloader-lang.sh"

log() { echo "[jdownloader-language] $*"; }

mkdir -p "${JD_CFG}" "${PROFILE_D}"

# Normalize
NORM="$(echo "${CODE}" | tr '[:upper:]' '[:lower:]')"
NORM="${NORM%%.*}"
NORM="${NORM%%@*}"

LOCALE=""; CHAIN=""; JD_CODE=""

case "${NORM}" in
    de|de_de)        LOCALE="de_DE.UTF-8"; JD_CODE="de_DE";;
    en|en_us)        LOCALE="en_US.UTF-8"; JD_CODE="en_US";;
    en_gb)           LOCALE="en_GB.UTF-8"; JD_CODE="en_GB";;
    fr|fr_fr)        LOCALE="fr_FR.UTF-8"; JD_CODE="fr_FR";;
    es|es_es)        LOCALE="es_ES.UTF-8"; JD_CODE="es_ES";;
    it|it_it)        LOCALE="it_IT.UTF-8"; JD_CODE="it_IT";;
    pt|pt_pt)        LOCALE="pt_PT.UTF-8"; JD_CODE="pt_PT";;
    pt_br)           LOCALE="pt_BR.UTF-8"; JD_CODE="pt_BR";;
    nl|nl_nl)        LOCALE="nl_NL.UTF-8"; JD_CODE="nl_NL";;
    pl|pl_pl)        LOCALE="pl_PL.UTF-8"; JD_CODE="pl_PL";;
    cs|cs_cz)        LOCALE="cs_CZ.UTF-8"; JD_CODE="cs_CZ";;
    sk|sk_sk)        LOCALE="sk_SK.UTF-8"; JD_CODE="sk_SK";;
    hu|hu_hu)        LOCALE="hu_HU.UTF-8"; JD_CODE="hu_HU";;
    ro|ro_ro)        LOCALE="ro_RO.UTF-8"; JD_CODE="ro_RO";;
    ru|ru_ru)        LOCALE="ru_RU.UTF-8"; JD_CODE="ru_RU";;
    tr|tr_tr)        LOCALE="tr_TR.UTF-8"; JD_CODE="tr_TR";;
    zh|zh_cn|zh_hans)LOCALE="zh_CN.UTF-8"; JD_CODE="zh_CN";;
    zh_tw|zh_hant)   LOCALE="zh_TW.UTF-8"; JD_CODE="zh_TW";;
    ja|ja_jp)        LOCALE="ja_JP.UTF-8"; JD_CODE="ja_JP";;
    ko|ko_kr)        LOCALE="ko_KR.UTF-8"; JD_CODE="ko_KR";;
    system|"")       LOCALE=""; JD_CODE="";;
    *)               LOCALE="${CODE}.UTF-8"; JD_CODE="${CODE}";;
esac

# Harden: only accept a safe locale-code charset (the *) fallback copies the raw
# user value). Anything else becomes "system" so it cannot break the seeded JSON
# or be interpolated unsafely downstream.
if [[ -n "${JD_CODE}" && ! "${JD_CODE}" =~ ^[A-Za-z]{2}([_-][A-Za-z0-9]{2,4})?$ ]]; then
    log "Ignoring unsafe JD_LANG value '${CODE}' – using system language"
    LOCALE=""; JD_CODE=""
fi

if [[ -z "${LOCALE}" ]]; then
    log "JD_LANG=system – removing forced language"
    rm -f "${ENV_FILE}"
    exit 0
fi

SHORT="${LOCALE%%_*}"
REGION="${LOCALE%%.*}"
if [[ "${SHORT}" == "en" ]]; then
    CHAIN="${REGION}:en"
else
    CHAIN="${REGION}:${SHORT}:en"
fi

log "Activating language: ${LOCALE} (JD_CODE=${JD_CODE})"

# Profile-Snippet (wird von der Shell und von KasmVNC sourced)
cat > "${ENV_FILE}" <<EOF
# Auto-generated by jdownloader-language.sh
export LANG=${LOCALE}
export LANGUAGE=${CHAIN}
export LC_ALL=${LOCALE}
EOF
chmod 644 "${ENV_FILE}"
ln -sf "${ENV_FILE}" /etc/profile.d/zz-jdownloader-lang.sh 2>/dev/null || true

# Seed JD's UI language ONLY on the first run (no WTFLocale.json yet). On later starts
# we deliberately leave it untouched, so a language the user picks in JDownloader's own
# language menu (Settings -> the flag icon) persists across container restarts.
LOCALE_JSON="${JD_CFG}/org.appwork.utils.locale.WTFLocale.json"
if [[ ! -f "${LOCALE_JSON}" ]]; then
    cat > "${LOCALE_JSON}" <<EOF
{"langCode":"${JD_CODE}","langFile":null,"dateFormat":null}
EOF
    log "Seeded UI language '${JD_CODE}' (first run) -> ${LOCALE_JSON}"
else
    log "UI language already set — leaving it as-is (change it in JD's own language menu)"
fi

log "Language set – LANG=${LOCALE} LANGUAGE=${CHAIN}"
exit 0
